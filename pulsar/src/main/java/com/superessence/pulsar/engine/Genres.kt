package com.superessence.pulsar.engine

enum class Family(val label: String) { CHILL("Chill"), MALADE("De malade") }

enum class Groove { NONE, BOOMBAP, HOUSE, SYNTHWAVE, TRAP, DRILL, PHONK, DNB, DUBSTEP, HARDSTYLE, HARDCORE, TECHNO, REGGAETON }
enum class BassStyle { DRONE, LOFI, WALKING, OFFBEAT, EIGHTHS, ROLLING, ACID, B808, REESE, WOBBLE, REVERSE, DEMBOW }
enum class ChordStyle { SUSTAIN, LOFI_COMP, STABS, PUMP, BROKEN, PLUCKS }
enum class Structure { CHILL, AMBIENT, CLUB, RAP, FESTIVAL }

class Genre(
    val id: String,
    val name: String,
    val family: Family,
    val tagline: String,
    val emoji: String,
    val colorA: Long,
    val colorB: Long,
    val bpmMin: Int,
    val bpmMax: Int,
    val swing: Float,
    val scales: List<Scale>,
    /** Progressions en degrés (0 = I/i). */
    val progressions: List<IntArray>,
    val chordExt: Int,
    val groove: Groove,
    val bassStyle: BassStyle,
    val chordStyle: ChordStyle,
    val structure: Structure,
    val kick: KickStyle,
    val snare: SnareStyle,
    val hatGain: Float,
    val bass: Patch,
    val chords: Patch,
    val lead: Patch,
    val arp: Patch,
    /** Probabilité d'arpège dans les sections actives. */
    val arpChance: Float,
    /** Densité de la mélodie (0..1). */
    val leadDensity: Float,
    val reverb: Float,
    val delay: Float,
    val vinyl: Float,
    val wow: Float,
    val rain: Float,
    /** Filtre passe-bas global « lo-fi » (Hz, 20000 = aucun). */
    val tone: Float,
    val sidechain: Float,
    val drive: Float,
    val halfTime: Boolean = false,
    val crush: Float = 0f,
    /** Gain de sortie (compense les genres très calmes). */
    val gain: Float = 1f,
)

