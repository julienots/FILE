#include "agr/ui/UIComponents.hpp"

#include "agr/scene/Reflection.hpp"

namespace agr {

void registerUIComponents() {
    auto& reg = ComponentRegistry::instance();
    if (reg.find<UICanvasComponent>()) return;
    reg.add<UICanvasComponent>("UICanvas")
        .category("UI")
        .description("Root of a game UI drawn over the scene; adapts to every screen size.")
        .field("scaleMode", &UICanvasComponent::scaleMode, {.enumEntries = {{"ConstantPixelSize", 0}, {"ScaleWithScreen", 1}}})
        .field("referenceResolution", &UICanvasComponent::referenceResolution, {.tooltip = "Design resolution (ScaleWithScreen)", .speed = 1.0f})
        .field("match", &UICanvasComponent::match, {.tooltip = "0 = follow the width, 1 = follow the height", .rangeMin = 0.0f, .rangeMax = 1.0f, .speed = 0.01f})
        .field("pixelScale", &UICanvasComponent::pixelScale, {.tooltip = "Pixels per unit (ConstantPixelSize)", .rangeMin = 0.1f, .rangeMax = 10.0f, .speed = 0.01f})
        .field("sortOrder", &UICanvasComponent::sortOrder, {.tooltip = "Higher canvases are drawn on top"})
        .field("respectSafeArea", &UICanvasComponent::respectSafeArea, {.tooltip = "Keep the UI away from notches and system bars (phones)"})
        .field("keyboardNavigation", &UICanvasComponent::keyboardNavigation, {.tooltip = "Arrows / D-pad move between controls, Enter / A activates"})
        .field("theme", &UICanvasComponent::theme, {.tooltip = "Look of the controls (.agrtheme)", .flags = FieldFlag_AssetPath});
    reg.add<UIRectComponent>("UIRect")
        .category("UI")
        .description("Position and size of a UI element relative to its parent (anchors, pivot).")
        .field("anchorMin", &UIRectComponent::anchorMin, {.tooltip = "0,0 = top-left of the parent; 1,1 = bottom-right", .rangeMin = 0.0f, .rangeMax = 1.0f, .speed = 0.01f})
        .field("anchorMax", &UIRectComponent::anchorMax, {.rangeMin = 0.0f, .rangeMax = 1.0f, .speed = 0.01f})
        .field("pivot", &UIRectComponent::pivot, {.rangeMin = 0.0f, .rangeMax = 1.0f, .speed = 0.01f})
        .field("position", &UIRectComponent::position, {.speed = 1.0f})
        .field("size", &UIRectComponent::size, {.tooltip = "Size (or extra size when the anchors are apart)", .speed = 1.0f})
        .field("scale", &UIRectComponent::scale, {.tooltip = "Around the pivot, children included", .speed = 0.01f})
        .field("rotation", &UIRectComponent::rotation, {.tooltip = "Around the pivot", .flags = FieldFlag_Angle})
        .field("screenRect", &UIRectComponent::screenRect, {.flags = FieldFlag_Hidden | FieldFlag_Transient | FieldFlag_ReadOnly});
    reg.add<UIImageComponent>("UIImage")
        .category("UI")
        .description("Colored or textured rectangle, with optional 9-slice borders.")
        .field("texture", &UIImageComponent::texture, {.tooltip = "Empty = plain color", .flags = FieldFlag_AssetPath})
        .field("color", &UIImageComponent::color, {.flags = FieldFlag_Color})
        .field("border", &UIImageComponent::border, {.tooltip = "9-slice borders in texture pixels: left, top, right, bottom", .speed = 1.0f})
        .field("borderScale", &UIImageComponent::borderScale, {.rangeMin = 0.01f, .rangeMax = 20.0f, .speed = 0.01f})
        .field("preserveAspect", &UIImageComponent::preserveAspect)
        .field("pixelArt", &UIImageComponent::pixelArt, {.tooltip = "Sharp pixels (nearest filtering)"})
        .field("blocksPointer", &UIImageComponent::blocksPointer, {.tooltip = "Off: clicks and touches go through the image"})
        .field("cornerRadius", &UIImageComponent::cornerRadius, {.tooltip = "Rounded corners (no texture), canvas units", .rangeMin = 0.0f, .rangeMax = 1000.0f, .speed = 0.25f})
        .field("outlineWidth", &UIImageComponent::outlineWidth, {.tooltip = "Outline inside the box (no texture), canvas units", .rangeMin = 0.0f, .rangeMax = 200.0f, .speed = 0.1f})
        .field("outlineColor", &UIImageComponent::outlineColor, {.flags = FieldFlag_Color})
        .field("shadowSize", &UIImageComponent::shadowSize, {.tooltip = "Soft drop shadow around the box (no texture), canvas units", .rangeMin = 0.0f, .rangeMax = 200.0f, .speed = 0.1f})
        .field("shadowColor", &UIImageComponent::shadowColor, {.flags = FieldFlag_Color})
        .field("shadowOffset", &UIImageComponent::shadowOffset, {.speed = 0.25f});
    reg.add<UITextComponent>("UIText")
        .category("UI")
        .description("Text with a TrueType font, aligned in its rectangle.")
        .field("text", &UITextComponent::text)
        .field("localizationKey", &UITextComponent::localizationKey,
               {.tooltip = "Clé de traduction (Affichage > Localisation) : remplace le texte selon la langue"})
        .field("font", &UITextComponent::font, {.tooltip = "TrueType font (.ttf)", .flags = FieldFlag_AssetPath})
        .field("fontSize", &UITextComponent::fontSize, {.tooltip = "Line height (canvas units)", .rangeMin = 1.0f, .rangeMax = 500.0f, .speed = 0.5f})
        .field("color", &UITextComponent::color, {.flags = FieldFlag_Color})
        .field("hAlign", &UITextComponent::hAlign, {.enumEntries = {{"Left", 0}, {"Center", 1}, {"Right", 2}}})
        .field("vAlign", &UITextComponent::vAlign, {.enumEntries = {{"Top", 0}, {"Middle", 1}, {"Bottom", 2}}})
        .field("wrap", &UITextComponent::wrap, {.tooltip = "Break lines at the rectangle's width"})
        .field("lineSpacing", &UITextComponent::lineSpacing, {.rangeMin = 0.5f, .rangeMax = 3.0f, .speed = 0.01f})
        .field("richText", &UITextComponent::richText, {.tooltip = "[color=#ff8800]...[/color], [b]...[/b], [u]...[/u]"});
    reg.add<UIButtonComponent>("UIButton")
        .category("UI")
        .description("Clickable / touchable element: calls onClick() on its script and a function of the target's script.")
        .field("interactable", &UIButtonComponent::interactable)
        .field("normalColor", &UIButtonComponent::normalColor, {.flags = FieldFlag_Color})
        .field("hoverColor", &UIButtonComponent::hoverColor, {.flags = FieldFlag_Color})
        .field("pressedColor", &UIButtonComponent::pressedColor, {.flags = FieldFlag_Color})
        .field("disabledColor", &UIButtonComponent::disabledColor, {.flags = FieldFlag_Color})
        .field("target", &UIButtonComponent::target, {.tooltip = "Entity whose script receives the message"})
        .field("message", &UIButtonComponent::message, {.tooltip = "Function of the target's script, called as target:message(button)"});
    reg.add<UISliderComponent>("UISlider")
        .category("UI")
        .description("Horizontal slider: calls onValueChanged(value) on its script and a function of the target's script.")
        .field("value", &UISliderComponent::value, {.speed = 0.01f})
        .field("minValue", &UISliderComponent::minValue, {.speed = 0.01f})
        .field("maxValue", &UISliderComponent::maxValue, {.speed = 0.01f})
        .field("wholeNumbers", &UISliderComponent::wholeNumbers)
        .field("interactable", &UISliderComponent::interactable)
        .field("vertical", &UISliderComponent::vertical, {.tooltip = "Bottom = min, top = max"})
        .field("trackColor", &UISliderComponent::trackColor, {.flags = FieldFlag_Color})
        .field("fillColor", &UISliderComponent::fillColor, {.flags = FieldFlag_Color})
        .field("handleColor", &UISliderComponent::handleColor, {.flags = FieldFlag_Color})
        .field("target", &UISliderComponent::target)
        .field("message", &UISliderComponent::message, {.tooltip = "Called as target:message(slider, value)"});
    reg.add<UIToggleComponent>("UIToggle")
        .category("UI")
        .description("Check box / radio button: onValueChanged(1 or 0); toggles of the same group are exclusive.")
        .field("isOn", &UIToggleComponent::isOn)
        .field("interactable", &UIToggleComponent::interactable)
        .field("group", &UIToggleComponent::group, {.tooltip = "Same group = radio buttons (one on at a time)"})
        .field("boxColor", &UIToggleComponent::boxColor, {.flags = FieldFlag_Color})
        .field("checkColor", &UIToggleComponent::checkColor, {.flags = FieldFlag_Color})
        .field("target", &UIToggleComponent::target)
        .field("message", &UIToggleComponent::message, {.tooltip = "Called as target:message(toggle, value)"});
    reg.add<UIInputFieldComponent>("UIInputField")
        .category("UI")
        .description("Text field (with a UIText): onTextChanged(text), onSubmit(text) on Enter; on-screen keyboard on phones.")
        .field("text", &UIInputFieldComponent::text)
        .field("placeholder", &UIInputFieldComponent::placeholder)
        .field("maxLength", &UIInputFieldComponent::maxLength)
        .field("numeric", &UIInputFieldComponent::numeric)
        .field("password", &UIInputFieldComponent::password)
        .field("multiline", &UIInputFieldComponent::multiline, {.tooltip = "Enter starts a new line"})
        .field("interactable", &UIInputFieldComponent::interactable)
        .field("textColor", &UIInputFieldComponent::textColor, {.flags = FieldFlag_Color})
        .field("placeholderColor", &UIInputFieldComponent::placeholderColor, {.flags = FieldFlag_Color})
        .field("target", &UIInputFieldComponent::target)
        .field("message", &UIInputFieldComponent::message, {.tooltip = "Called as target:message(field, text) on Enter"});
    reg.add<UIScrollViewComponent>("UIScrollView")
        .category("UI")
        .description("Scrolling area: children are the content, clipped; wheel or drag to scroll.")
        .field("vertical", &UIScrollViewComponent::vertical)
        .field("horizontal", &UIScrollViewComponent::horizontal)
        .field("scroll", &UIScrollViewComponent::scroll, {.speed = 1.0f})
        .field("wheelSpeed", &UIScrollViewComponent::wheelSpeed, {.rangeMin = 1.0f, .rangeMax = 1000.0f})
        .field("showScrollbar", &UIScrollViewComponent::showScrollbar)
        .field("scrollbarColor", &UIScrollViewComponent::scrollbarColor, {.flags = FieldFlag_Color});
    reg.add<UILayoutComponent>("UILayout")
        .category("UI")
        .description("Arranges the child elements in a column, a row or a grid.")
        .field("type", &UILayoutComponent::type, {.enumEntries = {{"Vertical", 0}, {"Horizontal", 1}, {"Grid", 2}}})
        .field("spacing", &UILayoutComponent::spacing, {.rangeMin = 0.0f, .rangeMax = 1000.0f, .speed = 0.5f})
        .field("padding", &UILayoutComponent::padding, {.tooltip = "left, top, right, bottom", .speed = 0.5f})
        .field("childAlignment", &UILayoutComponent::childAlignment, {.enumEntries = {{"Start", 0}, {"Center", 1}, {"End", 2}}})
        .field("expandChildren", &UILayoutComponent::expandChildren, {.tooltip = "Children fill the width (column) or height (row)"})
        .field("cellSize", &UILayoutComponent::cellSize, {.tooltip = "Grid cell size", .speed = 1.0f});
    reg.add<UIProgressBarComponent>("UIProgressBar")
        .category("UI")
        .description("Progress, health or loading bar.")
        .field("value", &UIProgressBarComponent::value, {.speed = 0.01f})
        .field("minValue", &UIProgressBarComponent::minValue, {.speed = 0.01f})
        .field("maxValue", &UIProgressBarComponent::maxValue, {.speed = 0.01f})
        .field("direction", &UIProgressBarComponent::direction,
               {.enumEntries = {{"LeftToRight", 0}, {"RightToLeft", 1}, {"BottomToTop", 2}, {"TopToBottom", 3}}})
        .field("backgroundColor", &UIProgressBarComponent::backgroundColor, {.flags = FieldFlag_Color})
        .field("fillColor", &UIProgressBarComponent::fillColor, {.flags = FieldFlag_Color})
        .field("inset", &UIProgressBarComponent::inset, {.rangeMin = 0.0f, .rangeMax = 100.0f, .speed = 0.1f});
    reg.add<UIDropdownComponent>("UIDropdown")
        .category("UI")
        .description("Drop-down list: calls onValueChanged(index) on its script and a function of the target's script.")
        .field("options", &UIDropdownComponent::options, {.tooltip = "Options separated by ';'"})
        .field("selected", &UIDropdownComponent::selected)
        .field("interactable", &UIDropdownComponent::interactable)
        .field("font", &UIDropdownComponent::font, {.flags = FieldFlag_AssetPath})
        .field("fontSize", &UIDropdownComponent::fontSize, {.rangeMin = 1.0f, .rangeMax = 300.0f, .speed = 0.5f})
        .field("boxColor", &UIDropdownComponent::boxColor, {.flags = FieldFlag_Color})
        .field("listColor", &UIDropdownComponent::listColor, {.flags = FieldFlag_Color})
        .field("highlightColor", &UIDropdownComponent::highlightColor, {.flags = FieldFlag_Color})
        .field("textColor", &UIDropdownComponent::textColor, {.flags = FieldFlag_Color})
        .field("target", &UIDropdownComponent::target)
        .field("message", &UIDropdownComponent::message, {.tooltip = "Called as target:message(dropdown, index)"});
    reg.add<UITabsComponent>("UITabs")
        .category("UI")
        .description("Tabs over pages: the i-th child is the page of the i-th tab.")
        .field("tabs", &UITabsComponent::tabs, {.tooltip = "Tab names separated by ';'"})
        .field("current", &UITabsComponent::current)
        .field("headerHeight", &UITabsComponent::headerHeight, {.rangeMin = 1.0f, .rangeMax = 500.0f})
        .field("font", &UITabsComponent::font, {.flags = FieldFlag_AssetPath})
        .field("fontSize", &UITabsComponent::fontSize, {.rangeMin = 1.0f, .rangeMax = 300.0f, .speed = 0.5f})
        .field("headerColor", &UITabsComponent::headerColor, {.flags = FieldFlag_Color})
        .field("activeColor", &UITabsComponent::activeColor, {.flags = FieldFlag_Color})
        .field("textColor", &UITabsComponent::textColor, {.flags = FieldFlag_Color})
        .field("target", &UITabsComponent::target)
        .field("message", &UITabsComponent::message, {.tooltip = "Called as target:message(tabs, index)"});
    reg.add<UITooltipComponent>("UITooltip")
        .category("UI")
        .description("Help text shown near the pointer when it rests on the element.")
        .field("text", &UITooltipComponent::text)
        .field("delay", &UITooltipComponent::delay, {.rangeMin = 0.0f, .rangeMax = 10.0f, .speed = 0.05f});
    reg.add<UIItemListComponent>("UIItemList")
        .category("UI")
        .description("List or tree of items: click selects (onValueChanged), double click activates (onSubmit), wheel / drag scrolls.")
        .field("items", &UIItemListComponent::items, {.tooltip = "Items separated by ';' (tree: leading '>' per level)"})
        .field("selected", &UIItemListComponent::selected)
        .field("tree", &UIItemListComponent::tree, {.tooltip = "Folding rows: '>' at the start of an item = one level deeper"})
        .field("collapsed", &UIItemListComponent::collapsed, {.tooltip = "Folded items (indices, comma-separated)"})
        .field("itemHeight", &UIItemListComponent::itemHeight, {.rangeMin = 4.0f, .rangeMax = 500.0f, .speed = 0.5f})
        .field("scroll", &UIItemListComponent::scroll, {.flags = FieldFlag_Transient})
        .field("interactable", &UIItemListComponent::interactable)
        .field("font", &UIItemListComponent::font, {.flags = FieldFlag_AssetPath})
        .field("fontSize", &UIItemListComponent::fontSize, {.rangeMin = 1.0f, .rangeMax = 300.0f, .speed = 0.5f})
        .field("backgroundColor", &UIItemListComponent::backgroundColor, {.flags = FieldFlag_Color})
        .field("selectedColor", &UIItemListComponent::selectedColor, {.flags = FieldFlag_Color})
        .field("textColor", &UIItemListComponent::textColor, {.flags = FieldFlag_Color})
        .field("target", &UIItemListComponent::target)
        .field("message", &UIItemListComponent::message);
    reg.add<UIDialogComponent>("UIDialog")
        .category("UI")
        .description("Modal dialog box (title, text, buttons): blocks the rest of the UI while open; a button closes it (onValueChanged(index)).")
        .field("open", &UIDialogComponent::open)
        .field("title", &UIDialogComponent::title)
        .field("text", &UIDialogComponent::text)
        .field("buttons", &UIDialogComponent::buttons, {.tooltip = "Buttons separated by ';'"})
        .field("size", &UIDialogComponent::size, {.speed = 1.0f})
        .field("result", &UIDialogComponent::result, {.flags = FieldFlag_ReadOnly | FieldFlag_Transient})
        .field("font", &UIDialogComponent::font, {.flags = FieldFlag_AssetPath})
        .field("fontSize", &UIDialogComponent::fontSize, {.rangeMin = 1.0f, .rangeMax = 300.0f, .speed = 0.5f})
        .field("panelColor", &UIDialogComponent::panelColor, {.flags = FieldFlag_Color})
        .field("dimColor", &UIDialogComponent::dimColor, {.flags = FieldFlag_Color})
        .field("buttonColor", &UIDialogComponent::buttonColor, {.flags = FieldFlag_Color})
        .field("textColor", &UIDialogComponent::textColor, {.flags = FieldFlag_Color})
        .field("target", &UIDialogComponent::target)
        .field("message", &UIDialogComponent::message);
    reg.add<UIColorPickerComponent>("UIColorPicker")
        .category("UI")
        .description("Color picker: saturation / brightness square, hue bar, alpha bar (onValueChanged).")
        .field("color", &UIColorPickerComponent::color, {.flags = FieldFlag_Color})
        .field("alpha", &UIColorPickerComponent::alpha)
        .field("interactable", &UIColorPickerComponent::interactable)
        .field("target", &UIColorPickerComponent::target)
        .field("message", &UIColorPickerComponent::message)
        .field("hsv", &UIColorPickerComponent::hsv, {.flags = FieldFlag_Hidden | FieldFlag_Transient})
        .field("hsvOf", &UIColorPickerComponent::hsvOf, {.flags = FieldFlag_Hidden | FieldFlag_Transient});
}

} // namespace agr
